export const signed = (value: number | null | undefined, digits = 2) =>
  value == null ? "--" : `${value >= 0 ? "+" : ""}${value.toFixed(digits)}`;
export const number = (value: number | null | undefined, digits = 2) =>
  value == null ? "--" : value.toLocaleString("zh-CN", { minimumFractionDigits: digits, maximumFractionDigits: digits });
export const money = (value: number | null | undefined, compactMode = false) => {
  if (value == null) return "--";
  const displayed = Math.abs(value) < 0.005 ? 0 : value;
  return `${displayed < 0 ? "−" : ""}$${compactMode ? compact.format(Math.abs(displayed)) : number(Math.abs(displayed), 2)}`;
};
export const localTime = (ts: number, withDate = false) => new Intl.DateTimeFormat(undefined, {
  month: withDate ? "short" : undefined, day: withDate ? "numeric" : undefined,
  hour: "2-digit", minute: "2-digit", second: withDate ? undefined : "2-digit",
}).format(new Date(ts * 1000));
export const statusLabel = (value: string) => labels[value.toLowerCase().replaceAll("-", "_")] ?? value;
